STATE_UPDATE_PROMPT = """
你将收到三部分内容：
1. 当前用户条目库：已有的用户事实条目（每行一条，形如「- 约束/事实」）。
2. 本轮事件：用户说了什么、AI 回复了什么。
3. 本轮工具调用：
   - 工具与参数：AI 实际调用的工具、填写的参数。
   - 执行结果（result）：工具真实返回的数据（可能为空）。

定位说明：
当前用户条目库是一个「压缩文本库」——每一行是一条独立的用户事实或关注点，
如「- 关注服务：svc-order」「- 关注级别：P0」「- 场景：值班排障」。

任务：对照「本轮事件」与「执行结果」，对该条目库做一次增/删/改，输出更新后的新库。

逐条处理规则：
- 未变化：原样保留。
- 被修改：用户改口（关注的服务、级别、场景）→ 用新值替换旧行。
- 被取消：用户明确表示不再关注 → 删除对应行。
- 被新增：本轮出现的新关注点/约束 → 新增一行。
- 执行结果能佐证的事实可写入；执行结果与对话矛盾时以真实结果为准。

补充规则：
1. 改口是最高优先级更新信号，必须覆盖旧值。
2. 只记录用户侧的关注点、约束、场景与决策进度等事实。
3. 不要记录 AI 回复里的服务介绍、状态数值与手册细节。

输出要求：
- 每行一条，换行分隔，格式统一为「- 内容」，无编号、无嵌套。
- 总长度控制在 200 个中文字以内；装不下时按重要性淘汰。
- 本轮没有新增用户信息时也要保留原有条目，不要清空。
- 只输出条目库文本，不要任何解释或前缀。
"""
